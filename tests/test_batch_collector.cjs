const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const model = vm.createContext({});
vm.runInContext(fs.readFileSync('browser-collector/batch-model.js','utf8'),model);
const call = expression=>vm.runInContext(expression,model);
model.user={id:9,login:'me'};
model.stacks=[{books:[{id:10,slug:'book',name:'Notes',user_id:9,items_count:3},{id:11,slug:'other',user_id:8,items_count:1}]}];
assert.equal(call('ownBooks(stacks,user).length'),1);
model.book={items_count:3};
model.rows=[{id:1,slug:'a',status:1,published_at:'2026-01-01'}, {id:2,slug:'b',status:0,published_at:'2026-01-01'}, {id:3,status:0,published_at:null}];
assert.equal(call('publishedRows(rows,book).length'),2);
model.book.items_count=4;
assert.throws(()=>call('publishedRows(rows,book)'),/数量/);
model.book.items_count=3;model.rows[2].id=2;
assert.throws(()=>call('publishedRows(rows,book)'),/重复/);
const html = toc=>`<script>decodeURIComponent("${encodeURIComponent(JSON.stringify({book:{toc},body_draft:'must not be retained'}))}")</script>`;
model.html=html([{uuid:'p',title:'Folder',secret:'omit'},{uuid:'c',parent_uuid:'p',doc_id:1,title:'Article'}]);
assert.equal(call('extractTOC(html)[1].parent_uuid'),'p');
assert.equal(call('extractTOC(html)[0].secret'),undefined);
model.html=html([{uuid:'a',parent_uuid:'missing'}]);
assert.throws(()=>call('extractTOC(html)'),/父节点/);
model.html=html([{uuid:'a',parent_uuid:'b'},{uuid:'b',parent_uuid:'a'}]);
assert.throws(()=>call('extractTOC(html)'),/循环/);
model.html='<html>login page</html>';
assert.throws(()=>call('extractTOC(html)'),/未识别/);
model.a={id:1,book_id:10,slug:'a',content:'same',content_modified:false};
model.b={...model.a,book_id:11};
assert.equal(call('sameCapture(a,b)'),false);
model.b={...model.a,deleted_at:'2026-10-27'};
assert.equal(call('sameCapture(a,b)'),false);
model.b={...model.a};assert.equal(call('sameCapture(a,b)'),true);
console.log('Batch ownership, count, draft exclusion, TOC and revision checks passed.');
